#!/usr/bin/env node
// Generates src/generated/runtime_modules.ts: the modules that run inside the
// sandbox (runtime, bridge, artifact API, UI kit), type-stripped with Node's
// built-in stripTypeScriptTypes and relinked to `sbx:/@sbx/...` keys.
//
//   node scripts/gen.mjs          write the file
//   node scripts/gen.mjs --check  exit 1 if the committed file is stale (CI)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";

process.removeAllListeners("warning");
process.on("warning", (w) => {
  if (w.name !== "ExperimentalWarning") console.warn(w);
});

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const OUT = join(SRC, "generated", "runtime_modules.ts");

/** Public names artifacts import → entry files. */
const PUBLIC = {
  "@panth977/sandbox/artifact": "artifact/artifact.ts",
  "@panth977/sandbox/stores": "artifact/stores.ts",
  "@panth977/sandbox/react": "artifact/react.ts",
  "@panth977/sandbox/ui": "ui/index.ts",
};
const RUNTIME = "runtime/runtime.ts";

const key = (rel) => "sbx:/@sbx/" + rel.replace(/\.ts$/, ".js");
// Only statements at the start of a line (comments may contain example imports).
const SPEC = /^(\s*(?:(?:import|export)\b[^"'\n]*?\bfrom\s*|\}\s*from\s*|import\s*))(["'])([^"']+)\2/gm;

const modules = new Map();
function visit(rel) {
  if (modules.has(rel)) return;
  const file = join(SRC, rel);
  if (!existsSync(file)) throw new Error(`missing ${rel}`);
  modules.set(rel, null);
  let js = stripTypeScriptTypes(readFileSync(file, "utf8"), { mode: "strip" });
  js = js.replace(SPEC, (m, pre, q, spec) => {
    if (!spec.startsWith(".")) throw new Error(`${rel}: runtime modules may only import relative files (got "${spec}")`);
    const target = relative(SRC, resolve(dirname(file), spec)).split("\\").join("/");
    visit(target);
    return `${pre}${q}${key(target)}${q}`;
  });
  // collapse the whitespace left where types were
  js = js.split("\n").map((l) => l.replace(/\s+$/, "")).filter((l, i, a) => l !== "" || a[i - 1] !== "").join("\n");
  modules.set(rel, js);
}
visit(RUNTIME);
for (const rel of Object.values(PUBLIC)) visit(rel);

const sorted = [...modules.keys()].sort();
let out = "// Generated by scripts/gen.mjs from src/**. Do not edit.\n";
out += "// The modules that run inside the sandbox, type-stripped and linked to sbx: keys.\n\n";
out += `/** Key of the module the loader starts. */\nexport const RUNTIME_ENTRY = ${JSON.stringify(key(RUNTIME))};\n\n`;
out += "/** Public import names → module keys. */\nexport const RUNTIME_SPECIFIERS: Record<string, string> = {\n";
for (const [name, rel] of Object.entries(PUBLIC)) out += `  ${JSON.stringify(name)}: ${JSON.stringify(key(rel))},\n`;
out += "};\n\n/** Module sources keyed by sbx: URL. */\nexport const RUNTIME_MODULES: Record<string, string> = {\n";
for (const rel of sorted) out += `  ${JSON.stringify(key(rel))}: ${JSON.stringify(modules.get(rel))},\n`;
out += "};\n";

// The same modules as TypeScript source, for the dev engine's language service
// (artifact authors get exact types for @panth977/sandbox/* imports).
const OUT_TYPES = join(SRC, "generated", "type_sources.ts");
let types = "// Generated by scripts/gen.mjs from src/**. Do not edit.\n";
types += "// TypeScript sources of the sandbox-side modules, for the dev engine's language service.\n\n";
types += "/** Public import names → source paths (relative to the package's src/). */\nexport const TYPE_ENTRIES: Record<string, string> = {\n";
for (const [name, rel] of Object.entries(PUBLIC)) types += `  ${JSON.stringify(name)}: ${JSON.stringify(rel)},\n`;
types += "};\n\n/** Source text by path relative to src/. */\nexport const TYPE_SOURCES: Record<string, string> = {\n";
for (const rel of sorted) types += `  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(join(SRC, rel), "utf8"))},\n`;
types += "};\n";

const outputs = [[OUT, out], [OUT_TYPES, types]];
if (process.argv.includes("--check")) {
  for (const [file, text] of outputs) {
    const cur = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (cur !== text) {
      console.error(`${relative(ROOT, file)} is stale: run node scripts/gen.mjs`);
      process.exit(1);
    }
  }
  console.log("generated files are current");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(`wrote src/generated: ${sorted.length} modules (${out.length} B js, ${types.length} B ts)`);
}
