// Screenshots for docs/review: node e2e/shots.mjs <outdir>
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { join } from "node:path";
import { serve } from "./server.mjs";
const pw = createRequire(join(process.env.PLAYWRIGHT_PATH ?? join(homedir(), ".cache/explainer-video/node_modules"), "x.js"))("playwright");
const out = process.argv[2] ?? "/tmp/sbx-shots";
const s = await serve(0);
const base = `http://127.0.0.1:${s.address().port}`;
const b = await pw.chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 1 });
const wait = () => p.waitForFunction(() => window.__results?.done, null, { timeout: 60000 });
await p.goto(`${base}/e2e/pages/ui.html`); await wait(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/ui-data.png`, fullPage: true });
const f = p.frameLocator("#slot iframe");
await f.locator("#org").click(); await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/ui-select.png` });
await f.locator("#org").press("Escape");
await f.locator("sbx-tabs button", { hasText: "Charts" }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/ui-charts.png`, fullPage: true });
await f.locator("sbx-tabs button", { hasText: "Forms" }).click(); await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/ui-forms.png`, fullPage: true });
await p.goto(`${base}/e2e/pages/ui.html?dark=1`); await wait(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/ui-dark.png`, fullPage: true });
await p.goto(`${base}/e2e/pages/dev.html`); await wait();
await p.waitForFunction(() => (document.querySelector(".sbx-dev__list")?.textContent ?? "").includes("not assignable"), null, { timeout: 90000 }).catch(() => {});
await p.evaluate(() => window.__dev.openFile("/App.tsx")); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/dev.png` });
await b.close(); s.close();
console.log("shots in", out);
